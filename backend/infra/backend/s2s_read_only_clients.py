"""The S2S APIs' read-only platform clients (app.shared.middleware.read_only_clients; optional, off by default).

`s2s-read-only-platform-client-id-params` in the environment config lists SSM parameters, each holding the id of
one Cognito app client that reads every project without a client assignment and may never write. The ids are
generated by Cognito, so the S2S stacks resolve them at deployment: the parameters must exist before the S2S
stacks deploy. Empty (the default): no environment variable, nothing changes.
"""

import aws_cdk
import constructs
from aws_cdk import aws_ssm

from app.shared.middleware import read_only_clients
from infra import config

CONFIG_KEY = "s2s-read-only-platform-client-id-params"


def parameter_names(app_config: config.AppConfig) -> list[str]:
    return list(app_config.environment_config.get(CONFIG_KEY) or [])


def environment(scope: constructs.Construct, app_config: config.AppConfig) -> dict[str, str]:
    """The S2S Lambda's S2S_READ_ONLY_PLATFORM_CLIENT_IDS, or nothing when none are configured."""
    names = parameter_names(app_config)
    if not names:
        return {}
    ids = [aws_ssm.StringParameter.value_for_string_parameter(scope, name) for name in names]
    return {read_only_clients.ENVIRONMENT_VARIABLE: aws_cdk.Fn.join(",", ids)}
